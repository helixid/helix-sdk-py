        assert encryptor.decrypt(stored, trail.evidence_aad("tool.call.arguments")) == b'{"orderId":"ORD-1"}'
        with pytest.raises(AuditEvidenceError):
            encryptor.decrypt(stored, trail.evidence_aad("tool.call.response"))
        committed = trail.evidence(b"bytes", "application/octet-stream", "p", commit_plaintext=True)
