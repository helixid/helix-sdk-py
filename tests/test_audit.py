    def test_sink_failure_consumes_the_sequence_but_keeps_the_predecessor(self) -> None:
        class Flaky:
            def __init__(self) -> None:
                self.entries: List[AuditTrailEntry] = []
                self.fail = False

            def append(self, entry: AuditTrailEntry) -> None:
                if self.fail:
                    raise RuntimeError("sink down")
                self.entries.append(entry)

        sink = Flaky()
        trail = make_trail(sink)
        first = trail.record(session_input())
        sink.fail = True
        with pytest.raises(RuntimeError, match="sink down"):
            trail.record(session_input())
        assert trail.sequence == 3 and trail.previous_source_event_digest == first.event_digest
        sink.fail = False
        third = trail.record(session_input())
        assert third.event["source"] == {**first.event["source"], "sourceSequence": "3", "previousSourceEventDigest": first.event_digest}
        assert [e.event["source"]["sourceSequence"] for e in sink.entries] == ["1", "3"]

    def test_evidence_through_the_trail(self) -> None:
        without = make_trail()
        with pytest.raises(AuditEvidenceError, match="no evidence vault"):
            without.evidence(b"x", "text/plain", "p")
        store = MemoryEvidenceStore()
        encryptor = EvidenceEncryptor(b"\x07" * 32, "key-1")
        trail = make_trail(evidence=AuditTrailEvidence(encryptor, store))
        ref = trail.evidence('{"orderId":"ORD-1"}', "application/json", "tool.call.arguments")
