class TestDigest:
    def test_digest_bytes_and_text(self) -> None:
        empty = "sha256:e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        assert digest_bytes(b"") == empty and digest_text("") == empty
        assert digest_bytes(bytearray(b"abc")) == digest_text("abc")
        assert DIGEST_PATTERN.fullmatch(digest_text("x"))

    def test_wtf8_bytes(self) -> None:
        assert wtf8_bytes("aé") == b"a\xc3\xa9"
        assert wtf8_bytes("\U0001f600") == b"\xf0\x9f\x98\x80"
        # Two surrogate code points that form a pair read as one character, as in UTF-16.
        assert wtf8_bytes("😀") == b"\xf0\x9f\x98\x80"
        # A lone surrogate is written as a three-byte code point of its own value.
        assert wtf8_bytes("\ud800") == b"\xed\xa0\x80"
        assert utf16_length("emoji-\U0001f600") == 8 and utf16_length("\ud800x") == 2

    def test_audit_digest_domain_separation(self) -> None:
        value = {"b": 1, "a": [1, 2]}
        assert audit_digest("d1", value) != audit_digest("d2", value)
        assert audit_digest("d1", value) == digest_bytes(b"d1\0" + canonicalize(value).encode())
        with pytest.raises(TypeError, match="non-empty"):
            audit_digest("", value)
        with pytest.raises(TypeError, match="NUL"):
            audit_digest("a\0b", value)
        with pytest.raises(CanonicalJsonError):
            audit_digest("d", {"x": float("nan")})

    def test_keyed_commitment_value(self) -> None:
        key = b"k" * 32
        value = keyed_commitment_value(key, "user@example.com")
        assert DIGEST_PATTERN.fullmatch(value)
        assert value == keyed_commitment_value(bytearray(key), "user@example.com")
        assert value != keyed_commitment_value(b"j" * 32, "user@example.com")
        assert value != keyed_commitment_value(key, "other@example.com")


