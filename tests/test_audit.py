        ciphertext = b64url_decode(sample["ciphertext_b64url"])
        aad = evidence_aad(sample["tenant"], sample["purpose"])
        assert aad == sample["aad_utf8"].encode("utf-8")
        encrypted = EncryptedEvidence(ref=sample["ref"], ciphertext=ciphertext)
        assert encryptor.decrypt(encrypted, aad) == sample["plaintext_utf8"].encode("utf-8")
        assert digest_bytes(ciphertext) == sample["ref"]["ciphertextDigest"]
        assert digest_bytes(aad) == sample["ref"]["encryption"]["aadDigest"]
