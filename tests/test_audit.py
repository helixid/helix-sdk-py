    def test_decrypt_refusals_in_order(self) -> None:
        encryptor = self.encryptor()
        encrypted = encryptor.encrypt(b"payload", "text/plain", self.AAD, commit_plaintext=True)
        ref = encrypted.ref

        def with_ref(**changes: Any) -> EncryptedEvidence:
            return EncryptedEvidence(ref={**ref, **changes}, ciphertext=encrypted.ciphertext)

        with pytest.raises(AuditEvidenceError, match="another suite or key") as other_key:
            encryptor.decrypt(with_ref(encryption={**ref["encryption"], "keyId": "key-2"}), self.AAD)
        assert other_key.value.details == {"keyId": "key-2"} and other_key.value.code == "AUDIT_EVIDENCE_INVALID"
        with pytest.raises(AuditEvidenceError, match="another suite or key"):
            encryptor.decrypt(with_ref(encryption={**ref["encryption"], "suite": "A128GCM"}), self.AAD)
        with pytest.raises(AuditEvidenceError, match="ciphertext does not match"):
            encryptor.decrypt(with_ref(ciphertextDigest="sha256:" + "0" * 64), self.AAD)
        with pytest.raises(AuditEvidenceError, match="ciphertext does not match"):
            encryptor.decrypt(with_ref(size="1"), self.AAD)
        with pytest.raises(AuditEvidenceError, match="authenticated data does not match"):
            encryptor.decrypt(encrypted, evidence_aad(TENANT, "other.purpose"))
        short = b"abc"
        with pytest.raises(AuditEvidenceError, match="shorter than its authentication tag"):
            encryptor.decrypt(EncryptedEvidence(ref={**ref, "ciphertextDigest": digest_bytes(short), "size": "3"}, ciphertext=short), self.AAD)
        # A ciphertext whose reference is consistent but whose tag does not verify (another key).
        with pytest.raises(AuditEvidenceError, match="AEAD verification failed"):
            EvidenceEncryptor(b"\x01" * 32, "key-1").decrypt(encrypted, self.AAD)
        with pytest.raises(AuditEvidenceError, match="AEAD verification failed"):
            encryptor.decrypt(with_ref(encryption={**ref["encryption"], "nonce": "!!"}), self.AAD)
        with pytest.raises(AuditEvidenceError, match="plaintext does not match its commitment"):
            encryptor.decrypt(with_ref(plaintextCommitment="sha256:" + "0" * 64), self.AAD)
        # The flipped byte of the fixture test, with the reference recomputed to match it: the AEAD refuses.
        flipped = bytes([encrypted.ciphertext[0] ^ 1]) + encrypted.ciphertext[1:]
        with pytest.raises(AuditEvidenceError, match="AEAD verification failed"):
            encryptor.decrypt(EncryptedEvidence(ref={**ref, "ciphertextDigest": digest_bytes(flipped)}, ciphertext=flipped), self.AAD)

